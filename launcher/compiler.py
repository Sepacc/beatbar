"""
compiler.py - Compilation engine for Beatbar Suite programs.

Builds standalone Windows executables using PyInstaller, embeds version metadata,
cleans up legacy versions in launcher/compiled/, and provides real-time progress logging.
"""

import os
import sys
import shutil
import subprocess
from typing import Dict, List, Optional, Tuple
from PyQt6.QtCore import QObject, pyqtSignal, QThread

from launcher.version_manager import (
    ProgramConfig, PROGRAM_REGISTRY, ROOT_DIR, LAUNCHER_DIR, COMPILED_DIR,
    read_source_version, parse_semver, clean_old_compiled_versions
)

TEMP_BUILD_DIR = os.path.join(LAUNCHER_DIR, "build_temp")


def is_pyinstaller_installed() -> bool:
    """Checks if PyInstaller is available in the current Python environment."""
    try:
        res = subprocess.run(
            [sys.executable, "-m", "PyInstaller", "--version"],
            capture_output=True,
            text=True,
            check=False
        )
        return res.returncode == 0
    except Exception:
        return False


def generate_version_info_file(prog: ProgramConfig, version_str: str, out_path: str) -> bool:
    """
    Generates a Windows PE Version Info file for PyInstaller to embed
    into the compiled executable.
    """
    semver = parse_semver(version_str)
    maj = semver[0] if len(semver) > 0 else 1
    min_ = semver[1] if len(semver) > 1 else 0
    rev = semver[2] if len(semver) > 2 else 0

    content = f"""# UTF-8
# VSVersionInfo block generated by Beatbar Launcher
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({maj}, {min_}, {rev}, 0),
    prodvers=({maj}, {min_}, {rev}, 0),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'Beatbar Suite'),
            StringStruct('FileDescription', '{prog.name}'),
            StringStruct('FileVersion', '{version_str}'),
            StringStruct('InternalName', '{prog.target_exe_name or prog.name}'),
            StringStruct('LegalCopyright', 'Beatbar Suite'),
            StringStruct('OriginalFilename', '{prog.target_exe_name or prog.name}'),
            StringStruct('ProductName', '{prog.name}'),
            StringStruct('ProductVersion', '{version_str}')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    try:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)
        return True
    except Exception as e:
        print(f"[Compiler] Error writing version info file: {e}")
        return False


def build_pyinstaller_command(prog: ProgramConfig, dist_dir: Optional[str] = None) -> Tuple[List[str], Optional[str]]:
    """Constructs the PyInstaller CLI arguments for compiling the target program."""
    target_dist = dist_dir or COMPILED_DIR
    os.makedirs(target_dist, exist_ok=True)
    os.makedirs(TEMP_BUILD_DIR, exist_ok=True)

    version_str = read_source_version(prog)
    version_info_path = os.path.join(TEMP_BUILD_DIR, f"{prog.id}_version_info.txt")
    generate_version_info_file(prog, version_str, version_info_path)

    cmd = [
        sys.executable,
        "-m", "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onefile",
        "--windowed",
        f"--name={os.path.splitext(prog.target_exe_name or 'Program')[0]}",
        f"--distpath={target_dist}",
        f"--workpath={TEMP_BUILD_DIR}",
        f"--specpath={TEMP_BUILD_DIR}",
    ]

    # Resolve Windows application icon from assets/icons/
    icon_svg = getattr(prog, "icon_svg", "") or prog.id
    candidate_icons = [
        os.path.join(ROOT_DIR, "assets", "icons", f"{icon_svg}.ico"),
        os.path.join(ROOT_DIR, "assets", "icons", f"beatbar-{icon_svg}.ico"),
        os.path.join(ROOT_DIR, "assets", f"{icon_svg}.ico"),
    ]
    for ico in candidate_icons:
        if os.path.exists(ico):
            cmd.append(f"--icon={ico}")
            break

    if os.path.exists(version_info_path):
        cmd.append(f"--version-file={version_info_path}")

    # Add shared assets
    assets_dir = os.path.join(ROOT_DIR, "assets")
    if os.path.exists(assets_dir):
        cmd.append(f"--add-data={assets_dir};assets")
    feather_dir = os.path.join(assets_dir, "feather")
    if not os.path.exists(feather_dir):
        feather_dir = os.path.join(ROOT_DIR, "feather")
    if os.path.exists(feather_dir):
        cmd.append(f"--add-data={feather_dir};feather")

    # Shared exclusions across all builds to prevent bundling unused heavy runtimes & Qt submodules
    global_excludes = [
        "torch", "torchvision", "torchaudio",
        "matplotlib", "pandas",
        "IPython", "jupyter", "notebook",
        "tkinter", "tcl", "_tkinter",
        "unittest", "doctest", "pdb",
        # Unused Qt6 modules
        "PyQt6.QtQml", "PyQt6.QtQuick", "PyQt6.QtQuick3D", "PyQt6.QtQuickWidgets",
        "PyQt6.QtPdf", "PyQt6.QtPdfWidgets",
        "PyQt6.QtSql", "PyQt6.QtBluetooth", "PyQt6.QtNfc",
        "PyQt6.QtPositioning", "PyQt6.QtSensors", "PyQt6.QtTest",
        "PyQt6.QtDesigner", "PyQt6.QtRemoteObjects", "PyQt6.QtWebChannel",
    ]
    for exc in global_excludes:
        cmd.append(f"--exclude-module={exc}")

    main_dir = os.path.join(ROOT_DIR, "main")

    # Program-specific configuration
    if prog.id == "beatbar_maker":
        cmd.extend([
            f"--paths={ROOT_DIR}",
            f"--paths={main_dir}",
            f"--add-data={main_dir};main",
            "--exclude-module=unittest",
            "--hidden-import=beat_generator",
            "--hidden-import=beat_format",
            "--hidden-import=zones_editor",
            "--hidden-import=icon_utils",
            "--hidden-import=cv2",
            "--hidden-import=numpy",
            "--hidden-import=scipy",
            "--hidden-import=scipy.signal",
            "--hidden-import=scipy._lib.array_api_compat",
            "--hidden-import=scipy._lib.array_api_compat.numpy",
            "--hidden-import=PyQt6",
            "--hidden-import=PyQt6.QtCore",
            "--hidden-import=PyQt6.QtGui",
            "--hidden-import=PyQt6.QtWidgets",
            "--hidden-import=PyQt6.QtMultimedia",
            "--hidden-import=PyQt6.QtMultimediaWidgets",
            "--hidden-import=PyQt6.QtSvg",
        ])
    elif prog.id == "beatbar_viewer":
        viewer_dir = os.path.join(ROOT_DIR, "viewer")
        web_dir = os.path.join(ROOT_DIR, "web")
        cmd.extend([
            f"--paths={ROOT_DIR}",
            f"--paths={viewer_dir}",
            f"--paths={main_dir}",
            f"--paths={web_dir}",
            f"--add-data={viewer_dir};viewer",
            f"--add-data={main_dir};main",
            f"--add-data={web_dir};web",
            "--hidden-import=viewer",
            "--hidden-import=viewer.viewer",
            "--hidden-import=viewer.beatbar",
            "--hidden-import=viewer.player_core",
            "--hidden-import=viewer.skin_manager",
            "--hidden-import=viewer.settings_dialog",
            "--hidden-import=viewer.ui_components",
            "--hidden-import=viewer.video_canvas",
            "--hidden-import=viewer.screen_shake",
            "--hidden-import=viewer.library_drawer",
            "--hidden-import=web",
            "--hidden-import=web.video_scanner",
            "--hidden-import=beat_format",
            "--hidden-import=icon_utils",
            "--hidden-import=PyQt6",
            "--hidden-import=PyQt6.QtSvg",
            "--hidden-import=PyQt6.QtMultimedia",
            # Exclude heavy DSP, CV, and ML packages from the viewer
            "--exclude-module=scipy",
            "--exclude-module=scipy.signal",
            "--exclude-module=librosa",
            "--exclude-module=numba",
            "--exclude-module=llvmlite",
            "--exclude-module=cv2",
            "--exclude-module=PIL",
            "--exclude-module=Pillow",
        ])
    elif prog.id == "beatbar_skins":
        beatpanel_dir = os.path.join(ROOT_DIR, "beatpanel")
        viewer_dir = os.path.join(ROOT_DIR, "viewer")
        cmd.extend([
            f"--paths={ROOT_DIR}",
            f"--paths={beatpanel_dir}",
            f"--paths={viewer_dir}",
            f"--paths={main_dir}",
            f"--add-data={beatpanel_dir};beatpanel",
            f"--add-data={viewer_dir};viewer",
            f"--add-data={main_dir};main",
            "--hidden-import=beatpanel",
            "--hidden-import=beatpanel.skin_maker_window",
            "--hidden-import=beatpanel.beatbar_preview",
            "--hidden-import=beatpanel.component_editor_widget",
            "--hidden-import=beatpanel.skin_data",
            "--hidden-import=beatpanel.svg_utils",
            "--hidden-import=beatpanel.theme_editor",
            "--hidden-import=icon_utils",
            "--hidden-import=PyQt6",
            "--hidden-import=PyQt6.QtSvg",
            # Exclude heavy packages & unused Multimedia
            "--exclude-module=scipy",
            "--exclude-module=librosa",
            "--exclude-module=numba",
            "--exclude-module=llvmlite",
            "--exclude-module=cv2",
            "--exclude-module=PIL",
            "--exclude-module=Pillow",
            "--exclude-module=PyQt6.QtMultimedia",
            "--exclude-module=PyQt6.QtMultimediaWidgets",
        ])
    elif prog.id == "launcher":
        launcher_ver = os.path.join(ROOT_DIR, "launcher", ".version")
        cmd.extend([
            f"--paths={ROOT_DIR}",
            "--hidden-import=launcher",
            "--hidden-import=launcher.launcher",
            "--hidden-import=launcher.version_manager",
            "--hidden-import=launcher.process_manager",
            "--hidden-import=launcher.compiler",
            "--hidden-import=launcher.compiler_dialog",
            "--hidden-import=launcher.beat_dropzone",
            "--hidden-import=launcher.skin_gallery",
            "--hidden-import=icon_utils",
            "--hidden-import=PyQt6",
            "--hidden-import=PyQt6.QtCore",
            "--hidden-import=PyQt6.QtGui",
            "--hidden-import=PyQt6.QtWidgets",
            "--hidden-import=PyQt6.QtSvg",
            "--exclude-module=numpy",
            "--exclude-module=scipy",
            "--exclude-module=librosa",
            "--exclude-module=numba",
            "--exclude-module=llvmlite",
            "--exclude-module=cv2",
            "--exclude-module=torch",
            "--exclude-module=PIL",
            "--exclude-module=Pillow",
            "--exclude-module=matplotlib",
            "--exclude-module=pandas",
            "--exclude-module=PyQt6.QtMultimedia",
            "--exclude-module=PyQt6.QtMultimediaWidgets",
        ])
        if os.path.exists(launcher_ver):
            cmd.append(f"--add-data={launcher_ver};launcher")

    cmd.append(prog.entry_script)
    return cmd, version_str


class CompilationWorker(QThread):
    """Background worker thread for running PyInstaller compilation without blocking UI."""
    log_signal = pyqtSignal(str)
    status_signal = pyqtSignal(str, int)  # status_msg, percent
    prog_finished = pyqtSignal(str, bool, str)  # prog_id, success, message
    all_finished = pyqtSignal()

    def __init__(self, prog_ids: List[str], parent=None):
        super().__init__(parent)
        self.prog_ids = prog_ids
        self._is_cancelled = False
        self._current_proc: Optional[subprocess.Popen] = None

    def cancel(self):
        self._is_cancelled = True
        if self._current_proc and self._current_proc.poll() is None:
            try:
                self._current_proc.terminate()
            except Exception:
                pass

    def run(self):
        total = len(self.prog_ids)
        if total == 0:
            self.all_finished.emit()
            return

        if not is_pyinstaller_installed():
            self.log_signal.emit("[Error] PyInstaller is not installed in the Python environment!")
            self.log_signal.emit("Please install PyInstaller via 'pip install pyinstaller'.")
            for pid in self.prog_ids:
                self.prog_finished.emit(pid, False, "PyInstaller not installed")
            self.all_finished.emit()
            return

        for idx, prog_id in enumerate(self.prog_ids):
            if self._is_cancelled:
                self.log_signal.emit("[Cancelled] Compilation aborted by user.")
                break

            prog = PROGRAM_REGISTRY.get(prog_id)
            if not prog:
                continue

            if prog.is_web or not prog.can_compile:
                self.log_signal.emit(f"[Notice] {prog.name} is a web application and is not compiled.")
                self.prog_finished.emit(prog_id, True, "Skipped (Web application)")
                continue

            percent = int((idx / total) * 100)
            self.status_signal.emit(f"Compiling {prog.name}...", percent)
            self.log_signal.emit("=" * 60)
            self.log_signal.emit(f"Starting compilation for: {prog.name} ({prog_id})")

            # 1. Clean old versions
            self.log_signal.emit(f"Cleaning previous versions in {COMPILED_DIR}...")
            cleaned = clean_old_compiled_versions(prog)
            if cleaned:
                for c in cleaned:
                    self.log_signal.emit(f"  Removed obsolete build file: {os.path.basename(c)}")
            else:
                self.log_signal.emit("  No old files found to clean.")

            # 2. Build PyInstaller command
            cmd, source_version = build_pyinstaller_command(prog)
            self.log_signal.emit(f"Target Version: v{source_version}")
            self.log_signal.emit(f"Executing: {' '.join(cmd[:6])} ...")

            success = False
            error_msg = ""
            try:
                self._current_proc = subprocess.Popen(
                    cmd,
                    cwd=ROOT_DIR,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.STDOUT,
                    text=True,
                    bufsize=1,
                    universal_newlines=True
                )

                for line in iter(self._current_proc.stdout.readline, ""):
                    if self._is_cancelled:
                        break
                    line_str = line.strip()
                    if line_str:
                        self.log_signal.emit(line_str)

                self._current_proc.stdout.close()
                return_code = self._current_proc.wait()

                if self._is_cancelled:
                    success = False
                    error_msg = "Compilation cancelled by user"
                elif return_code == 0:
                    success = True
                    # Write companion .version in launcher/compiled/
                    comp_ver_path = os.path.join(COMPILED_DIR, f"{os.path.splitext(prog.target_exe_name)[0]}.version")
                    with open(comp_ver_path, "w", encoding="utf-8") as vf:
                        vf.write(source_version)
                    self.log_signal.emit(f"[Success] Compiled {prog.name} (v{source_version}) successfully!")
                else:
                    success = False
                    error_msg = f"PyInstaller failed with exit code {return_code}"
                    self.log_signal.emit(f"[Error] {error_msg}")

            except Exception as e:
                success = False
                error_msg = str(e)
                self.log_signal.emit(f"[Exception] {e}")

            # Clean temporary build directory
            if os.path.exists(TEMP_BUILD_DIR):
                try:
                    shutil.rmtree(TEMP_BUILD_DIR, ignore_errors=True)
                except Exception:
                    pass

            self.prog_finished.emit(prog_id, success, error_msg or f"Compiled v{source_version}")

        self.status_signal.emit("All tasks completed", 100)
        self.all_finished.emit()


def compile_headless(program_ids: List[str]):
    from launcher.version_manager import PROGRAM_REGISTRY
    for prog_id in program_ids:
        if prog_id not in PROGRAM_REGISTRY:
            print(f"Unknown program: {prog_id}")
            continue
        prog = PROGRAM_REGISTRY[prog_id]
        if not prog.can_compile:
            print(f"Cannot compile {prog.name}")
            continue
        print("=" * 60)
        print(f"Compiling {prog.name} ({prog.id})...")
        clean_old_compiled_versions(prog)
        cmd, source_version = build_pyinstaller_command(prog)
        print(f"Version: v{source_version}")
        print(f"Running PyInstaller...")
        res = subprocess.run(cmd, cwd=ROOT_DIR)
        if res.returncode == 0:
            comp_ver_path = os.path.join(COMPILED_DIR, f"{os.path.splitext(prog.target_exe_name)[0]}.version")
            with open(comp_ver_path, "w", encoding="utf-8") as vf:
                vf.write(source_version)
            print(f"[SUCCESS] Compiled {prog.name} (v{source_version}) successfully!\n")
        else:
            print(f"[ERROR] Failed to compile {prog.name} with code {res.returncode}\n")
        if os.path.exists(TEMP_BUILD_DIR):
            shutil.rmtree(TEMP_BUILD_DIR, ignore_errors=True)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Headless PyInstaller compiler for Beatbar Suite")
    parser.add_argument("programs", nargs="*", help="Program IDs to compile (beatbar_maker, beatbar_viewer, beatbar_skins, launcher). Use 'all' for all.")
    args = parser.parse_args()

    if not args.programs or "all" in args.programs:
        targets = ["launcher", "beatbar_maker", "beatbar_viewer", "beatbar_skins"]
    else:
        targets = args.programs
    compile_headless(targets)

